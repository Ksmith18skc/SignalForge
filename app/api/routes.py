def _best_book_timestamp_from_rows(
    rows: list[dict[str, Any]] | None,
    *,
    book: str | None,
    line: float | None,
    timestamp_key: str,
    book_key: str,
) -> str | None:
    if not rows or not book:
        return None
    candidates: list[datetime] = []
    for row in rows:
        if str(row.get(book_key) or "") != book:
            continue
        if line is not None:
            try:
                row_line = float(row.get("line"))
            except (TypeError, ValueError):
                row_line = None
            if row_line is not None and abs(row_line - line) > 0.0001:
                continue
        ts = _parse_dt(row.get(timestamp_key))
        if ts:
            candidates.append(ts)
    if not candidates:
        return None
    return max(candidates).isoformat()


def _source_url_from_rows(
    rows: list[dict[str, Any]] | None,
    *,
    book: str | None,
    side: str | None,
    line: float | None,
) -> str | None:
    if not rows or not book or not side:
        return None
    side_key = str(side).lower()
    for row in rows:
        if str(row.get("bookmaker") or "") != book:
            continue
        if line is not None:
            try:
                row_line = float(row.get("line"))
            except (TypeError, ValueError):
                row_line = None
            if row_line is not None and abs(row_line - line) > 0.0001:
                continue
        links = row.get("direct_links") or {}
        if isinstance(links, dict):
            link = links.get(side_key)
            if link:
                return str(link)
    return None


def _edge_payload_with_context(db: Session, edge: MlbEdge) -> dict[str, object]:
    payload = edge_to_dict(edge)
    game = db.scalar(select(MlbGame).where(MlbGame.game_pk == edge.game_pk))
    if game:
        payload["game_date"] = game.game_date
        payload["game_start_time"] = game.start_time.isoformat() if game.start_time else None
        # Surface team names so the dashboard can render compact "NYY @ KC"
        # titles for game totals/moneyline/spread cards without re-parsing
        # the slug. Pure display enrichment; no scoring impact.
        payload["home_team"] = game.home_team
        payload["away_team"] = game.away_team

    now = datetime.utcnow()
    if edge.edge_type == "pitcher_strikeouts":
        snap = _latest_prop_snapshot(db, edge.game_pk)
        if snap:
            payload["odds_snapshot_captured_at"] = snap.captured_at.isoformat() if snap.captured_at else None
            payload["odds_snapshot_source"] = snap.source
            payload["best_book_updated_at"] = _best_book_timestamp_from_rows(
                snap.rows,
                book=edge.best_book,
                line=edge.line,
                timestamp_key="timestamp",
                book_key="sportsbook",
            )
            age_minutes = int((now - snap.captured_at).total_seconds() / 60) if snap.captured_at else None
            payload["odds_data_age_minutes"] = age_minutes
            payload["odds_stale"] = bool(age_minutes is not None and age_minutes > MLB_PITCHER_PROPS_TTL.total_seconds() / 60)
    else:
        snap = _latest_odds_snapshot(db, edge.game_pk)
        if snap:
            payload["odds_snapshot_captured_at"] = snap.captured_at.isoformat() if snap.captured_at else None
            payload["odds_snapshot_source"] = snap.source
            payload["best_book_updated_at"] = _best_book_timestamp_from_rows(
                snap.rows,
                book=edge.best_book,
                line=edge.line,
                timestamp_key="updated_at",
                book_key="bookmaker",
            )
            payload["source_url"] = _source_url_from_rows(
                snap.rows,
                book=edge.best_book,
                side=edge.side,
                line=edge.line,
            )
            age_minutes = int((now - snap.captured_at).total_seconds() / 60) if snap.captured_at else None
            payload["odds_data_age_minutes"] = age_minutes
            payload["odds_stale"] = bool(age_minutes is not None and age_minutes > MLB_TOTALS_TTL.total_seconds() / 60)

    # --- explainability: history + calibration for the card's #4/#5 sections.
    band = lookup_edge_score_band(db, edge_type=edge.edge_type, score=edge.score)
    payload["score_band_performance"] = band
    payload["calibrated_probability"] = band.get("calibrated_probability")
    # SignalForge fair probability when the model exposes one (often None until
    # the projection is calibrated); the card falls back to calibrated prob.
    factors = edge.factors or {}
    for key in ("model_probability", "fair_probability", "model_prob", "p_fair"):
        val = factors.get(key) if isinstance(factors, dict) else None
        if val is not None:
            try:
                payload["sf_fair_probability"] = float(val)
            except (TypeError, ValueError):
                pass
            break
    return payload


