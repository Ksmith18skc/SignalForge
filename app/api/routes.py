def _database_backend(database_url: str) -> str:
    scheme = database_url.split(":", 1)[0].lower() if database_url else ""
    if scheme.startswith("sqlite"):
        return "sqlite"
    if scheme.startswith("postgres") or scheme.startswith("postgresql"):
        return "postgres"
    return "unknown"


