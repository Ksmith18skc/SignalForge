@router.post("/mlb/edges/update-closing-lines")
def mlb_update_closing_lines(
    payload: dict[str, object],
    db: Session = Depends(get_db),
) -> dict[str, object]:
    updates = payload.get("updates")
    if not isinstance(updates, list):
        raise HTTPException(status_code=400, detail="payload must include updates list")
    updated = 0
    missing: list[int] = []
    for row in updates:
        if not isinstance(row, dict):
            continue
        edge_id = row.get("edge_id") or row.get("id")
        if edge_id is None:
            continue
        edge = db.get(MlbEdge, int(edge_id))
        if edge is None:
            missing.append(int(edge_id))
            continue
        update_closing_line_fields(
            edge,
            closing_line=_optional_float(row.get("closing_line")),
            closing_price=_optional_float(row.get("closing_price")),
        )
        updated += 1
    db.commit()
    return {"updated": updated, "missing_edge_ids": missing}


def _perf_window(days: int | None, date: str | None) -> tuple[str | None, str | None]:
    """Resolve (start, end) Arizona dates from ?days= and ?date= params.

    - ``date`` (single day) wins when provided.
    - ``days`` (rolling window ending today AZ) is used otherwise.
    - When neither is provided, returns (None, None) for all-time.
    """
    if date:
        return date, date
    if days and days > 0:
        return arizona_window(days)
    return None, None


